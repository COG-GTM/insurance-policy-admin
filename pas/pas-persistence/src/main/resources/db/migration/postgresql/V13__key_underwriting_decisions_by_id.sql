-- AB-521: fix quirk Q-18. DB2 keys UNDERWRITING_DECISIONS by (POLICY_NUMBER, DECISION_DATE), so a
-- second decision on the same day is lost. The target keys each decision by a generated id and
-- keeps every row. Existing rows keep their values and get ids on migration.
-- During dual-run the CDC sink merges rows that come from DB2 on (policy_number, decision_date),
-- which DB2 still guarantees unique (AB-529); rows written by Java only ever insert.

ALTER TABLE acmeins.underwriting_decisions
    ADD COLUMN decision_id bigint GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE acmeins.underwriting_decisions DROP CONSTRAINT pk_uw_decisions;

ALTER TABLE acmeins.underwriting_decisions
    ADD CONSTRAINT pk_uw_decisions PRIMARY KEY (decision_id);

CREATE INDEX ix_uwd_policy_date
    ON acmeins.underwriting_decisions (policy_number, decision_date, created_timestamp);
